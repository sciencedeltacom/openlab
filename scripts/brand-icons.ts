/**
 * Regenerates `src/lib/brand-icons.ts` from simpleicons.org.
 *
 * The icons are brand marks for the services the app names: cloud stores, accounts, MCP
 * servers and public research APIs. They are CC0, but they are also *remote* — so they are
 * fetched here, once, and committed. The app draws them from its own bundle and never calls
 * the CDN.
 *
 * Run with `bun scripts/brand-icons.ts` and commit the result. A slug is the brand's title,
 * lowercased with everything but letters and digits removed (`Google Drive` → `googledrive`).
 * A slug the CDN does not know is reported and skipped: the interface falls back to a letter
 * tile, so a missing icon is a smaller mark, not a broken build.
 */

const SOURCE = 'https://cdn.simpleicons.org';
const OUT = 'src/lib/brand-icons.ts';

/** Every mark the interface draws, grouped by where it appears. */
const SLUGS = [
  // Accounts
  'google',
  'github',
  // Cloud stores
  'googledrive',
  'huggingface',
  'zenodo',
  'figshare',
  'osf',
  // Object-store presets
  'cloudflare',
  'backblaze',
  'wasabi',
  'digitalocean',
  'minio',
  // Notebook kernels
  'python',
  // MCP servers
  'zotero',
  // Public research APIs
  'pubmed',
  'arxiv',
];

interface Icon {
  title: string;
  hex: string;
  path: string;
}

const icons: Record<string, Icon> = {};
const missing: string[] = [];

for (const slug of SLUGS) {
  const response = await fetch(`${SOURCE}/${slug}`);
  if (!response.ok) {
    missing.push(`${slug} (${response.status})`);
    continue;
  }
  const svg = await response.text();
  const title = /<title>([^<]*)<\/title>/.exec(svg)?.[1] ?? slug;
  const hex = /fill="(#[0-9A-Fa-f]{6})"/.exec(svg)?.[1] ?? '#000000';
  const path = /<path d="([^"]+)"/.exec(svg)?.[1];
  if (!path) {
    missing.push(`${slug} (no path)`);
    continue;
  }
  icons[slug] = { title, hex, path };
}

const body = Object.entries(icons)
  .map(
    ([slug, icon]) =>
      `  ${slug}: {\n    title: ${JSON.stringify(icon.title)},\n    hex: '${icon.hex}',\n    path: '${icon.path}',\n  },`,
  )
  .join('\n');

const file = `/**
 * Brand marks, generated by \`bun scripts/brand-icons.ts\` — do not edit by hand.
 *
 * Each entry is one icon from simpleicons.org (CC0): its title, its brand colour, and the
 * single path of its 24×24 mark. They are here rather than fetched because the app has to
 * draw them offline, and a request per card would be a request per card.
 */

/** One brand's mark. */
export interface BrandIcon {
  title: string;
  /** The brand's own colour, as \`#RRGGBB\`. */
  hex: string;
  /** The mark's path, on a 24×24 viewBox. */
  path: string;
}

/** Every mark, by slug. */
export const BRAND_ICONS: Record<string, BrandIcon> = {
${body}
};
`;

await Bun.write(OUT, file);

console.log(`wrote ${OUT}: ${Object.keys(icons).length} icons`);
if (missing.length > 0) {
  console.log(`not in the CDN, letter tile instead: ${missing.join(', ')}`);
}
